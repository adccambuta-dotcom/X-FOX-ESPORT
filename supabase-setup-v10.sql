create table if not exists public.matches (
 id bigint generated by default as identity primary key,
 division text not null check (division in ('AO','EU')),
 match_date date,
 opponent text not null,
 result text not null default '',
 outcome text not null default 'Partida',
 notes text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.training_sessions (
 id bigint generated by default as identity primary key,
 title text not null,
 division text not null check (division in ('AO','EU','BOTH')),
 session_date date,
 session_time text not null default '',
 location text not null default '',
 description text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.news_posts (
 id bigint generated by default as identity primary key,
 title text not null,
 body text not null,
 image_url text not null default '',
 published boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.gallery_items (
 id bigint generated by default as identity primary key,
 image_url text not null,
 caption text not null default '',
 published boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.recruitment_applications (
 id bigint generated by default as identity primary key,
 full_name text not null,
 ml_nickname text not null,
 email text not null,
 division text not null check (division in ('AO','EU')),
 game_role text not null,
 rank text not null default '',
 message text not null default '',
 status text not null default 'pending' check (status in ('pending','reviewing','approved','rejected')),
 created_at timestamptz not null default now()
);

alter table public.matches enable row level security;
alter table public.training_sessions enable row level security;
alter table public.news_posts enable row level security;
alter table public.gallery_items enable row level security;
alter table public.recruitment_applications enable row level security;

drop policy if exists "Public read matches" on public.matches;
create policy "Public read matches" on public.matches for select to anon, authenticated using (true);
drop policy if exists "Admins manage matches" on public.matches;
create policy "Admins manage matches" on public.matches for all to authenticated using (public.xfox_is_admin()) with check (public.xfox_is_admin());

drop policy if exists "Public read training" on public.training_sessions;
