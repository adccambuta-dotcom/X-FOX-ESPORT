-- Cria catálogo de heróis, estatísticas por herói/jogador e gestão de torneios.

create table if not exists public.heroes_catalog (
  id bigint generated by default as identity primary key,
  name text not null unique,
  image_url text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.player_hero_stats (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  hero_id bigint not null references public.heroes_catalog(id) on delete cascade,
  win_rate numeric(5,2) not null check (win_rate >= 0 and win_rate <= 100),
  matches_played integer not null default 0 check (matches_played >= 0),
  updated_at timestamptz not null default now(),
  unique(profile_id, hero_id)
);

create table if not exists public.tournaments (
  id bigint generated by default as identity primary key,
  name text not null,
  division text not null check (division in ('AO','EU','BOTH')),
  event_date date,
  status text not null default 'Próximo torneio',
  placement text not null default '',
  description text not null default '',
  url text not null default '',
  created_at timestamptz not null default now()
);

alter table public.heroes_catalog enable row level security;
alter table public.player_hero_stats enable row level security;
alter table public.tournaments enable row level security;

drop policy if exists "Public read hero catalogue" on public.heroes_catalog;
create policy "Public read hero catalogue" on public.heroes_catalog for select to anon, authenticated using (true);
drop policy if exists "Admins manage hero catalogue" on public.heroes_catalog;
create policy "Admins manage hero catalogue" on public.heroes_catalog for all to authenticated using (public.xfox_is_admin()) with check (public.xfox_is_admin());

drop policy if exists "Public read approved hero stats" on public.player_hero_stats;
create policy "Public read approved hero stats" on public.player_hero_stats for select to anon, authenticated using (exists(select 1 from public.profiles p where p.id=profile_id and p.status='approved' and p.is_admin=false));
drop policy if exists "Admins manage player hero stats" on public.player_hero_stats;
create policy "Admins manage player hero stats" on public.player_hero_stats for all to authenticated using (public.xfox_is_admin()) with check (public.xfox_is_admin());

drop policy if exists "Public read tournaments" on public.tournaments;
create policy "Public read tournaments" on public.tournaments for select to anon, authenticated using (true);
drop policy if exists "Admins manage tournaments" on public.tournaments;
create policy "Admins manage tournaments" on public.tournaments for all to authenticated using (public.xfox_is_admin()) with check (public.xfox_is_admin());

